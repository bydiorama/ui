import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

// The REAL resolver, imported the way the command imports it from a
// checkout — so these tests break if the stylesheet composition and the CLI
// ever disagree, not only if the CLI's own plumbing does.
import * as tokens from "../../tokens/src/index.ts";
import {
  nodeThemeIo,
  pickSeed,
  resolveTokensEntry,
  runTheme,
  themeHeader,
  ThemeCommandError,
  type ThemeIo,
  type TokensModule,
} from "./theme.ts";

const CWD = resolve("/app");
const CHECKOUT = resolve(import.meta.dirname, "../../..");

const BRAND = {
  colors: {
    bg: "#f3f1ec", surface: "#ffffff", muted: "#efebe5", border: "#e5dfd6",
    textPrimary: "#1c1a17", textMuted: "#6b655c", accent: "#c2410c",
  },
};

/** The structural slice compiles against the real module — a drift in
 *  either signature fails type-check here. */
const TOKENS: TokensModule = tokens;

function memoryIo(seedModule: Record<string, unknown>, files: Record<string, string> = {}): ThemeIo & { files: Record<string, string> } {
  return {
    files,
    loadTokens: async () => TOKENS,
    loadSeedModule: async () => seedModule,
    readFile: async (path) => files[path] ?? null,
    writeFile: async (path, content) => {
      files[path] = content;
    },
  };
}

test("theme writes exactly theme-zero.css's composition for the given seed, under its own GENERATED header", async () => {
  const io = memoryIo({ seed: BRAND });
  const result = await runTheme({ cwd: CWD, seed: "theme/brand.ts", out: "src/brand.css" }, io);
  assert.equal(result.status, "written");

  const css = io.files[resolve(CWD, "src/brand.css")]!;
  const header = themeHeader({ seedLabel: "theme/brand.ts", outLabel: "src/brand.css", scheme: "auto" });
  assert.equal(css, tokens.toThemeStylesheet(tokens.resolveThemePair(BRAND), { header, scheme: "auto" }));
  // …and that composition is the three calls build-theme-css.mjs has always made.
  assert.ok(css.endsWith(`${tokens.toTailwindTheme()}\n\n${tokens.toCss(tokens.resolveThemePair(BRAND), { scope: ":root", scheme: "auto" })}`));
  assert.match(css, /^\/\*\n \* Brand theme/);
  assert.ok(css.includes("GENERATED by `bydiorama-ui theme`"));
  assert.ok(css.includes(" *   bydiorama-ui theme --seed theme/brand.ts --out src/brand.css\n"), "the header names the regenerate command");
});

test("theme-zero.css is the same composition — the registry item and the command cannot drift", async () => {
  const shipped = await readFile(join(CHECKOUT, "registry/themes/theme-zero/theme-zero.css"), "utf8");
  const pair = tokens.resolveThemePair(tokens.THEME_ZERO, { authored: tokens.ZERO_AUTHORED });
  const body = `${tokens.toTailwindTheme()}\n\n${tokens.toCss(pair, { scope: ":root", scheme: "auto" })}`;
  assert.ok(shipped.endsWith(body));
});

test("--scheme forces the scheme and is recorded in the regenerate command", async () => {
  const io = memoryIo({ default: BRAND });
  const result = await runTheme({ cwd: CWD, seed: "brand.json", out: "brand.css", scheme: "dark" }, io);
  const css = io.files[resolve(CWD, "brand.css")]!;
  assert.equal(result.command, "bydiorama-ui theme --seed brand.json --out brand.css --scheme dark");
  assert.ok(css.includes("color-scheme: dark;"));
  assert.ok(!css.includes("color-scheme: light dark;"));
  await assert.rejects(runTheme({ cwd: CWD, seed: "b.json", out: "b.css", scheme: "dim" as never }, io), ThemeCommandError);
});

test("--check: current when the file matches, stale when it does not or is missing — and it never writes", async () => {
  const io = memoryIo({ seed: BRAND });
  await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css" }, io);
  const out = resolve(CWD, "brand.css");
  const written = io.files[out]!;

  assert.equal((await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css", check: true }, io)).status, "current");

  io.files[out] = written.replace("--ui-bg-base", "--ui-bg-based");
  assert.equal((await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css", check: true }, io)).status, "stale");
  assert.notEqual(io.files[out], written, "--check must not repair the file");

  // A changed seed makes a once-current file stale.
  io.files[out] = written;
  const darker = memoryIo({ seed: { ...BRAND, colors: { ...BRAND.colors, accent: "#7c2d12" } } }, io.files);
  assert.equal((await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css", check: true }, darker)).status, "stale");

  delete io.files[out];
  assert.equal((await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css", check: true }, io)).status, "stale");
});

test("an unsafe seed is rejected and nothing is written; an info issue still writes", async () => {
  const hostile = memoryIo({ seed: { colors: { ...BRAND.colors, accent: "#fff; } body { display: none" } } });
  const rejected = await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css" }, hostile);
  assert.equal(rejected.status, "rejected");
  assert.ok(rejected.issues.some((i) => i.path === "colors.accent" && i.severity === "error"));
  assert.deepEqual(hostile.files, {});

  const small = memoryIo({ seed: { ...BRAND, typography: { baseSize: 13 } } });
  const written = await runTheme({ cwd: CWD, seed: "brand.ts", out: "brand.css" }, small);
  assert.equal(written.status, "written");
  assert.ok(written.issues.some((i) => i.path === "typography.baseSize" && i.severity === "info"));
});

test("pickSeed: --export, then default, then seed, then the only seed-shaped export — ambiguity is an error", () => {
  assert.equal(pickSeed({ default: BRAND, seed: {} }).exportName, "default");
  assert.equal(pickSeed({ seed: BRAND }).exportName, "seed");
  assert.equal(pickSeed({ ACME: BRAND, helper: 3 }).exportName, "ACME");
  assert.equal(pickSeed({ a: BRAND, b: BRAND }, "b").exportName, "b");
  assert.throws(() => pickSeed({ a: BRAND, b: BRAND }), /--export/);
  assert.throws(() => pickSeed({ helper: 3 }), /no ThemeSeed/);
  assert.throws(() => pickSeed({ a: BRAND }, "nope"), /no export `nope`/);
  assert.throws(() => pickSeed({ a: { colours: {} } }, "a"), /not a ThemeSeed/);
});

test("tokens resolve from --registry-path, else from the checkout the CLI runs in, else a clear error", () => {
  const checkoutBin = pathToFileURL(join(CHECKOUT, "packages/cli/bin/ui.ts")).href;
  const entry = join(CHECKOUT, "packages/tokens/src/index.ts");
  const exists = (path: string) => path === entry;

  assert.equal(resolveTokensEntry({ registryPath: CHECKOUT, cliModuleUrl: "file:///elsewhere/bin/ui.js", exists }), entry);
  assert.equal(resolveTokensEntry({ cliModuleUrl: checkoutBin, exists }), entry);
  assert.throws(() => resolveTokensEntry({ registryPath: "/not-a-checkout", cliModuleUrl: checkoutBin, exists }), /is it a bydiorama\/ui checkout/);

  // Published: the CLI runs from node_modules, where the tokens are neither
  // installed (unpublished, issue #30) nor importable (Node will not strip
  // TypeScript there) — even if a file happens to exist at the sibling path.
  const published = pathToFileURL("/app/node_modules/@bydiorama/ui/dist/bin/ui.js").href;
  assert.throws(() => resolveTokensEntry({ cliModuleUrl: published, exists: () => true }), /issue #30[\s\S]*--registry-path/);
});

test("the node loader reads a .json seed and imports a .ts seed whose type imports are erased", async () => {
  const dir = await mkdtemp(join(tmpdir(), "ui-theme-"));
  try {
    await writeFile(join(dir, "brand.json"), JSON.stringify(BRAND));
    await writeFile(
      join(dir, "brand.ts"),
      `import type { ThemeSeed } from "@bydiorama/tokens";\nexport const ACME: ThemeSeed = ${JSON.stringify(BRAND)};\n`,
    );
    const io = nodeThemeIo(join(CHECKOUT, "packages/tokens/src/index.ts"));
    for (const seed of ["brand.json", "brand.ts"]) {
      const result = await runTheme({ cwd: dir, seed, out: `out/${seed}.css` }, io);
      assert.equal(result.status, "written", seed);
      const css = await readFile(join(dir, `out/${seed}.css`), "utf8");
      assert.ok(css.includes(`--ui-bg-base: light-dark(${tokens.resolveThemePair(BRAND).light["--ui-bg-base"]}`), seed);
    }
    await assert.rejects(io.loadSeedModule(join(dir, "missing.json")), /No seed file/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
