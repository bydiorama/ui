#!/usr/bin/env node
// Generates two trees from `registry/skills/`:
//
//   .claude/skills/       every skill — what agents working in this repo load
//   plugins/ui/skills/    the shipped skills — the `ui` agent plugin (ADR 0027)
//
// plus the plugin's README, which lists its skills from their front matter so
// the list cannot drift from what ships.
//
// `--check` verifies freshness without writing — the same contract as
// `build-registry.mjs`, and for the same reason: a generated artifact that is
// committed must be provably current, or reviewers start trusting a stale copy.
//
// Files are written BYTE-IDENTICAL to their source. A "generated, do not edit"
// banner inside the file would make the copy differ from what a consumer
// installs, so the warning lives in the generated READMEs and in this script's
// failure message instead.

import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, rmSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { ROOT } from "./lib/manifest.mjs";
import {
  readSkills, installName, skillReferences, firstSentence,
  SKILL_INSTALL_DIR, SKILL_SOURCE_DIR, PLUGIN_DIR, PLUGIN_SKILLS_DIR, PLUGIN_NAME,
} from "./lib/skills.mjs";

const LOCAL_README = `# Generated — do not edit

Every file here is copied from \`registry/skills/<dir>/\` (SKILL.md and any
reference files beside it) by
\`pnpm skills:build\`. Edit the source, not this copy; \`pnpm check:skills\`
fails if the two drift.

Skills live in one tree so there is one source of truth. The manifest — not
the folder — decides which of them ship: those are also generated into the
\`${PLUGIN_NAME}\` agent plugin, \`plugins/${PLUGIN_NAME}/\`. See
\`ledger/decisions/0013-skills.md\` and \`ledger/decisions/0027-agent-plugin.md\`.
`;

const check = process.argv.includes("--check");
const skills = readSkills().filter((s) => s.source);
const shipped = skills.filter((s) => s.isDistributed);

function pluginReadme() {
  const rows = shipped
    .map((s) => `| \`${PLUGIN_NAME}:${installName(s)}\` | ${firstSentence(s.parsed?.fields.description ?? "").replaceAll("|", "\\|")} |`)
    .join("\n");
  return `<!-- Generated by \`pnpm skills:build\` from registry/skills/ and ui.manifest.json — do not edit. -->

# \`${PLUGIN_NAME}\` — the Diorama UI agent plugin

Agent skills for building with [\`@bydiorama/ui\`](https://github.com/bydiorama/ui):
apps, Paper designs, and demo videos and stills of the UI. Claude shows each
skill as \`${PLUGIN_NAME}:<skill>\`.

| Skill | What it is for |
|---|---|
${rows}

## Install

Claude Code:

\`\`\`
/plugin marketplace add bydiorama/ui
/plugin install ${PLUGIN_NAME}@diorama-ui
\`\`\`

claude.ai and Cowork: **Customize › Plugins › Add › Add marketplace**, enter
\`bydiorama/ui\`, then add the \`${PLUGIN_NAME}\` plugin. The plugin has no version
number, so it follows \`main\`; turn on automatic updates for the
\`diorama-ui\` marketplace.

If an app still has skills the CLI copied in (\`.claude/skills/diorama-*\`),
delete them and their entries in \`ui.lock.json\`, so the two copies don't compete.

## Changing a skill

Never here. The source is \`registry/skills/<skill>/\` in bydiorama/ui; this
folder is regenerated by \`pnpm skills:build\` and \`pnpm check:skills\` fails on
drift. The \`create-skill\` skill in that repo has the rules.
`;
}

/** path → contents. */
const expected = new Map([
  [join(SKILL_INSTALL_DIR, "README.md"), LOCAL_README],
  [join(PLUGIN_DIR, "README.md"), pluginReadme()],
]);
for (const skill of skills) {
  const roots = [join(SKILL_INSTALL_DIR, installName(skill))];
  if (skill.isDistributed) roots.push(join(PLUGIN_SKILLS_DIR, installName(skill)));
  for (const root of roots) {
    expected.set(join(root, "SKILL.md"), skill.source);
    // Reference files travel with their skill, byte for byte (Buffers, so binaries survive).
    for (const rel of skillReferences(skill)) {
      expected.set(join(root, rel), readFileSync(join(SKILL_SOURCE_DIR, skill.dir, rel)));
    }
  }
}

/** Every file under a generated tree, so removals are caught too. */
function filesUnder(dir) {
  const out = [];
  const walk = (d) => {
    if (!existsSync(d)) return;
    for (const name of readdirSync(d)) {
      const full = join(d, name);
      if (statSync(full).isDirectory()) walk(full);
      else out.push(full);
    }
  };
  walk(dir);
  return out;
}
const generatedTrees = [SKILL_INSTALL_DIR, PLUGIN_SKILLS_DIR];
const actualFiles = () => [...generatedTrees.flatMap(filesUnder), ...[join(PLUGIN_DIR, "README.md")].filter(existsSync)];

if (check) {
  const stale = [];
  for (const [path, contents] of expected) {
    if (!existsSync(path)) stale.push(`${relative(ROOT, path)} (missing)`);
    else if (!readFileSync(path).equals(Buffer.from(contents))) stale.push(`${relative(ROOT, path)} (differs from source)`);
  }
  for (const path of actualFiles()) {
    if (!expected.has(path)) stale.push(`${relative(ROOT, path)} (not generated from any skill)`);
  }

  if (stale.length) {
    console.error("Generated skills are stale:\n");
    for (const s of stale) console.error(`  - ${s}`);
    console.error(
      "\nEdit registry/skills/<dir>/SKILL.md — the source — then run `pnpm skills:build`.",
    );
    process.exit(1);
  }
  console.log(`skills up to date (${expected.size} file(s), ${shipped.length} skill(s) in the ${PLUGIN_NAME} plugin)`);
} else {
  // Remove first, so a renamed or deleted skill does not linger and keep
  // loading into every agent that opens this repo — or every app with the
  // plugin. The plugin's hand-written manifest is outside the cleared tree.
  for (const dir of generatedTrees) if (existsSync(dir)) rmSync(dir, { recursive: true });
  for (const [path, contents] of expected) {
    mkdirSync(join(path, ".."), { recursive: true });
    writeFileSync(path, contents);
    console.log(`wrote ${relative(ROOT, path)}`);
  }
}
