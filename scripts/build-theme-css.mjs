#!/usr/bin/env node
// Emit theme zero as an installable stylesheet: registry/themes/theme-zero/theme-zero.css
//
//   pnpm theme:build          write it
//   pnpm check:theme-css      fail if it is stale (part of `pnpm verify`)
//
// Why a FILE in the registry and not only the `@bydiorama/tokens` package
// (issue #30): the package is unpublished, so every consumer so far resolved
// `../ui/packages/tokens/src/index.ts` by path from a script and committed the
// output. This is that output, generated here once, from the same two emitter
// calls Storybook renders against — `toTailwindTheme()` and `toCss()` — and
// installed like any other item. A brand theme still goes through the
// emitters (`resolveThemePair` → `toCss`); this is theme zero only.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { ROOT } from "./lib/manifest.mjs";

const { resolveThemePair, toCss, toTailwindTheme, THEME_ZERO, ZERO_AUTHORED } = await import(
  join(ROOT, "packages/tokens/src/index.ts")
);

const OUT = join(ROOT, "registry/themes/theme-zero/theme-zero.css");

const pair = resolveThemePair(THEME_ZERO, { authored: ZERO_AUTHORED });
const css = [
  "/*",
  " * Theme zero — the @bydiorama/ui token layer and the Tailwind v4 theme that",
  " * maps utilities onto it. GENERATED by scripts/build-theme-css.mjs from",
  " * @bydiorama/tokens; do not edit — reinstall the `theme-zero-css` item.",
  " *",
  " * Import it once, after `@import \"tailwindcss\";`, in the stylesheet",
  " * Tailwind compiles. Light and dark follow prefers-color-scheme.",
  " */",
  "",
  toTailwindTheme(),
  "",
  toCss(pair, { scope: ":root", scheme: "auto" }),
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    // missing counts as stale
  }
  if (current !== css) {
    console.error("✗ registry/themes/theme-zero/theme-zero.css is stale — run `pnpm theme:build`.");
    process.exit(1);
  }
  console.log("✓ theme-zero.css matches the token emitters");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, css);
  console.log(`wrote registry/themes/theme-zero/theme-zero.css (${css.split("\n").length} lines)`);
}
